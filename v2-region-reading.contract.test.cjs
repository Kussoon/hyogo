'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = __dirname, window = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'v2-regions.js'), 'utf8'), {window});
const regions = window.KussoonHyogoV2Regions.regions;
assert.equal(regions.length, 10);
const codes = regions.flatMap(region => region.codes);
assert.equal(codes.length, 49);
assert.equal(new Set(codes).size, 49);
for (const region of regions) assert.ok(region.name && /^[ぁ-ゖー]+$/.test(region.reading), region.key);
const html = fs.readFileSync(path.join(root, 'v2-study-region.html'), 'utf8');
assert.match(html, /fetch\('\/v2\/progressive-preview\/label-index\.json'\)/);
assert.match(html, /new Set\(codes\)\.size!==49\|\|codes\.some\(code=>!byCode\.has\(code\)\)/);
assert.match(html, /if\(region\.reading\)ruby\.append\(make\('rt',region\.reading\)\)/);
assert.match(html, /if\(entry\.reading\)ruby\.append\(make\('rt',entry\.reading\)\)/);
assert.match(html, /button\.onclick=\(\)=>select\(region\)/);
assert.doesNotMatch(html, /id="map"|d3@|topojson-client/);
assert.match(html, /v2-quiz1\.html/);
assert.match(html, /v2-quiz2\.html/);
console.log('Hyogo 10 regions and 49 municipality list contract: OK');
